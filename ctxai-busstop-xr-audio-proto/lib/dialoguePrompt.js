/**
 * 이번 턴의 user 메시지를 만든다.
 * 변하는 값은 전부 여기에 담긴다 — 시스템 프롬프트는 건드리지 않는다.
 */
export function buildTurnMessage({ state, utterance, intent, elapsed, stageId, timeRemaining }) {
  const reveal = REVEAL_BRIEF[Math.min(state.revealLevel ?? 0, 3)];
  const frozen = state.revealFrozen;
  const lines = [
    "## 지금 장면",
    STAGE_BRIEF[stageId] || "정류장에 앉아 있습니다.",
    "",
    "## 지금 상태",
    `- 경과: ${Math.floor(elapsed)}초 / 남은 시간: ${timeRemaining}초`,
    `- 신뢰도: ${state.trust} / 100`,
    `- 정서적 압력: ${state.tension} / 100`,
    `- 공개 단계: ${state.revealLevel} / 3`,
    "",
    "## 이번 턴에 말해도 되는 범위",
    reveal,
  ];

  if (frozen) {
    lines.push(
      "",
      "**공개 단계가 동결되었습니다.** 버스가 오고 있습니다. 새 비밀·새 화제·새 질문을 열지 말고, 무엇을 물어도 이별로 수렴시키십시오."
    );
  }

  lines.push("", "## 관객의 반응", INTENT_BRIEF[intent] || INTENT_BRIEF.unknown);

  if (utterance && utterance.trim()) {
    lines.push(`관객이 한 말: "${utterance.trim()}"`);
  } else {
    lines.push("(발화 없음)");
  }

  lines.push(
    "",
    "위 범위 안에서, 인물로서 할 다음 대사 한 줄을 주십시오. 1~2문장, 최대 60자."
  );

  return lines.join("\n");
}

/**
 * 모델 응답이 규칙을 어겼는지 검사한다.
 *
 * 소개서 §11 의 "AI 가 바꾸면 안 되는 것"을 코드로 강제하는 자리다.
 * 프롬프트만으로는 보장이 안 되므로, 채택 전에 반드시 통과시킨다.
 * 실패하면 호출자가 사전 녹음 브리지 대사로 대체한다.
 */
export function validateReply(reply, { state, timeRemaining }) {
  if (!reply || typeof reply.text !== "string") return { ok: false, reason: "형식 오류" };

  const text = reply.text.trim();
  if (!text) return { ok: false, reason: "빈 대사" };
  if (text.length > 90) return { ok: false, reason: "대사 과다 (90자 초과)" };

  // 내부 태그·마크다운·지시문이 새어나온 경우
  if (/[<>]/.test(text)) return { ok: false, reason: "태그 유출" };
  if (/^[*#\-]/.test(text)) return { ok: false, reason: "마크다운 유출" };

  // 인물이 깨진 경우
  if (/\b(AI|GPT|Claude|모델|프롬프트|시스템)\b/i.test(text)) {
    return { ok: false, reason: "메타 발화" };
  }

  // 공개 단계를 넘어선 경우 — 아직 열리지 않은 정보의 키워드를 차단한다
  const level = state.revealLevel ?? 0;
  if (level < 2 && /(헤어|이별|끝냈|정리했|결별)/.test(text)) {
    return { ok: false, reason: `공개 단계 ${level}에서 관계 종료 언급` };
  }

  // 버스 접근 이후 새 질문을 여는 경우
  if (timeRemaining <= 40 && /[?？]/.test(text) && !/버스|가요|먼저/.test(text)) {
    return { ok: false, reason: "동결 구간에서 새 질문" };
  }

  return { ok: true };
}
